class PCM8U(modem.ICodec[bytes]):
    def decode(self, data: bytes) -> list[float]:
        return [DECODE_TABLE[byte] for byte in data]
    
    def encode(self, samples: list[float]) -> bytes:
        def encode_sample(sample: float) -> float:
            pcm16 = int(round(sample * 32767))
            sign = 1 if sample < 0 else 0
            abs_pcm = abs(pcm16)
            abs_pcm = min(abs_pcm + 33, 32767)
            lut_idx = (abs_pcm >> 7)

            if lut_idx > 255:
                lut_idx = 255

            exponent = EXP_LUT[lut_idx]
            mantissa = ((abs_pcm) >> (exponent + 3)) & 0x0f
            ulaw = ((sign << 7) | (exponent << 4) | mantissa)
            ulaw = (~ulaw) & 0xff

            return ulaw
        
        return bytes(encode_sample(sample) for sample in samples)
